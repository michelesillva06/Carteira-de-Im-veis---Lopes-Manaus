/**
 * Translates an array of amenities and removes duplicates while preserving quality.
 */
export function translateAmenitiesList(features: string[] | undefined | null): string[] {
  if (!features || !Array.isArray(features)) return [];
  const translated = features
    .map((f) => translateAmenity(f))
    .filter((f) => Boolean(f) && f.trim().length > 0);

  // Remove duplicates while keeping order
  return Array.from(new Set(translated));
}
